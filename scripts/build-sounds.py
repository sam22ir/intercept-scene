"""Build src/audioAssets.js from the sound effects generated with ElevenLabs (eleven_text_to_sound_v2).

Usage: python scripts/build-sounds.py DIR     (DIR holds boom, hiss, clunk, launch, splash, engine, booster,
                                               motor, wind, surf, hum as .mp3; needs numpy, scipy, soundfile, ffmpeg)
One-shots are normalised and kept as mono mp3. Loops are cross-faded into seamless loops and stored as small PCM
wavs (an mp3 loop can click at its encoder padding); the engine pitch is a playback rate in the app.
"""
import base64, subprocess, sys, tempfile, os
import numpy as np, soundfile as sf

SRC = sys.argv[1]
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'audioAssets.js')
tmp = tempfile.mkdtemp()
ONE_SHOTS = ['boom', 'hiss', 'clunk', 'launch', 'splash']
LOOPS = {'engine': 16000, 'booster': 16000, 'motor': 16000, 'wind': 16000, 'hum': 8000}   # name: wav sample rate
MP3_LOOPS = ['surf']                                                                       # long noise bed


def run(*a): subprocess.run(a, check=True, capture_output=True)


def decode(name, sr):
    wav = os.path.join(tmp, name + '.wav')
    run('ffmpeg', '-y', '-i', os.path.join(SRC, name + '.mp3'), '-ac', '1', '-ar', str(sr), wav)
    return sf.read(wav)[0]


def norm(x, peak=0.84): return x * (peak / (np.abs(x).max() + 1e-12))


def loop(x, sr, xf=0.15):
    n = int(xf * sr); w = np.linspace(0, np.pi / 2, n)
    return np.concatenate([x[:n] * np.sin(w) + x[-n:] * np.cos(w), x[n:-n]])


def b64(path): return base64.b64encode(open(path, 'rb').read()).decode()


assets = {}
for name in ONE_SHOTS:
    x = norm(decode(name, 32000)); p = os.path.join(tmp, name + '.out.wav'); sf.write(p, x, 32000)
    m = os.path.join(tmp, name + '.mp3'); run('ffmpeg', '-y', '-i', p, '-codec:a', 'libmp3lame', '-b:a', '56k', m)
    assets[name] = (b64(m), 'audio/mpeg')
for name in MP3_LOOPS:
    x = loop(norm(decode(name, 32000)), 32000, 0.4); p = os.path.join(tmp, name + '.out.wav'); sf.write(p, x, 32000)
    m = os.path.join(tmp, name + '.mp3'); run('ffmpeg', '-y', '-i', p, '-codec:a', 'libmp3lame', '-b:a', '48k', m)
    assets[name] = (b64(m), 'audio/mpeg')
for name, sr in LOOPS.items():
    x = decode(name, sr)
    p = os.path.join(tmp, name + '.pcm.wav'); sf.write(p, loop(norm(x), sr), sr, subtype='PCM_16')
    assets[name] = (b64(p), 'audio/wav')
    print(name, 'loop', round(len(x) / sr, 2), 's')

with open(OUT, 'w') as f:
    f.write("// Generated by scripts/build-sounds.py from sound effects made with ElevenLabs text-to-sound v2.\n")
    f.write("// Mono, embedded as base64 so the offline build needs no files.\n")
    f.write("export const SOUNDS = {\n" + ''.join(f"  {k}: '{v[0]}',\n" for k, v in assets.items()) + "};\n")
print('wrote', os.path.getsize(OUT) // 1024, 'kB')
