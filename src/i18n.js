// The interface language (English or French) and the main menu's own words in both. Pure: it imports
// nothing and only reads storage inside try. The language is chosen in the main menu's Settings and
// remembered in localStorage['intercept.lang']. The menu re-renders itself when it changes; `menuText` and `ui`
// read the stored language when they are called, so a mission started afterwards uses it.

export const LANGS = [
  { id: 'en', name: 'English', short: 'EN' },
  { id: 'fr', name: 'Français', short: 'FR' },
];
export const LANG_KEY = 'intercept.lang';

export function readLang() {
  try {
    const v = globalThis.localStorage?.getItem(LANG_KEY);
    if (v === 'en' || v === 'fr') return v;
  } catch { /* storage unavailable */ }
  return 'en';
}
export const LANG = readLang();

export function saveLang(id) {
  try { globalThis.localStorage?.setItem(LANG_KEY, id); } catch { /* storage unavailable */ }
}

